"""Builds "liquid glass" style home screen icons from the flat logo.

Usage: python3 scripts/glass-icon.py assets/app-icon.svg <out dir>
Writes app-icon-glass.svg (iOS, with an edge rim), app-icon-glass-android.svg
and app-icon-glass-maskable.svg (glyph shrunk into Android's safe zone).
"""
import re, sys
src = open(sys.argv[1]).read()
out_dir = sys.argv[2]

paths = re.findall(r'<path\s+class="[de]"\s+d="([^"]+)"', src)
rects = re.findall(r'<rect\s+class="d"\s+x="([\d.]+)"\s+y="([\d.]+)"\s+width="([\d.]+)"\s+height="([\d.]+)"', src)
assert len(paths) == 2 and len(rects) == 2, (len(paths), len(rects))

# The glyph's original placement inside the 100x100 icon
GLYPH_TRANSFORM = "translate(-232.87972,-177.71009) matrix(0.22835737,0,0,0.22835737,79.049671,201.39648)"
shapes = "".join(f'<path d="{d}"/>' for d in paths) + "".join(
    f'<rect x="{x}" y="{y}" width="{w}" height="{h}"/>' for x, y, w, h in rects
)

def icon(rim: bool, scale: float) -> str:
    glyph_wrap = (
        f"translate(50 50) scale({scale}) translate(-50 -50) {GLYPH_TRANSFORM}"
        if scale != 1 else GLYPH_TRANSFORM
    )
    rim_svg = """
  <rect x="0.6" y="0.6" width="98.8" height="98.8" rx="22" fill="none"
        stroke="url(#rim)" stroke-width="1.2"/>""" if rim else ""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="1024" height="1024">
  <!-- Generated by scripts/glass-icon.py from assets/app-icon.svg -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#0563c9"/>
      <stop offset="1" stop-color="#009245"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.22" cy="0.12" r="0.75">
      <stop offset="0" stop-color="#fff" stop-opacity="0.26"/>
      <stop offset="0.55" stop-color="#fff" stop-opacity="0.06"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="shade" cx="0.85" cy="0.95" r="0.6">
      <stop offset="0" stop-color="#002a18" stop-opacity="0.12"/>
      <stop offset="1" stop-color="#002a18" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="body" x1="0" y1="0.25" x2="0" y2="0.8">
      <stop offset="0" stop-color="#fff" stop-opacity="0.96"/>
      <stop offset="1" stop-color="#f2fff8" stop-opacity="0.8"/>
    </linearGradient>
    <linearGradient id="edge" x1="0" y1="0" x2="0.35" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="1"/>
      <stop offset="0.45" stop-color="#fff" stop-opacity="0.15"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0.65"/>
    </linearGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.75"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.75"/>
      <stop offset="0.35" stop-color="#fff" stop-opacity="0.08"/>
      <stop offset="0.7" stop-color="#fff" stop-opacity="0.04"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0.45"/>
    </linearGradient>
    <filter id="blur-shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur stdDeviation="1.6"/>
    </filter>
    <filter id="inner-light" x="-10%" y="-10%" width="120%" height="120%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="0.9" result="blur"/>
      <feOffset in="blur" dy="1.1" result="down"/>
      <feComposite in="SourceAlpha" in2="down" operator="out" result="top-edge"/>
      <feFlood flood-color="#fff" flood-opacity="0.95"/>
      <feComposite in2="top-edge" operator="in" result="top-light"/>
      <feOffset in="blur" dy="-0.9" result="up"/>
      <feComposite in="SourceAlpha" in2="up" operator="out" result="bottom-edge"/>
      <feFlood flood-color="#fff" flood-opacity="0.5"/>
      <feComposite in2="bottom-edge" operator="in" result="bottom-light"/>
      <feMerge><feMergeNode in="top-light"/><feMergeNode in="bottom-light"/></feMerge>
    </filter>
    <mask id="glyph-mask">
      <g transform="{glyph_wrap}" fill="#fff">{shapes}</g>
    </mask>
  </defs>

  <rect width="100" height="100" fill="url(#bg)"/>
  <rect width="100" height="100" fill="url(#glow)"/>
  <rect width="100" height="100" fill="url(#shade)"/>

  <!-- soft shadow under the glass -->
  <g transform="translate(0 1.8)" opacity="0.35" filter="url(#blur-shadow)">
    <g transform="{glyph_wrap}" fill="#00331c">{shapes}</g>
  </g>

  <!-- frosted glass body -->
  <rect width="100" height="100" fill="url(#body)" mask="url(#glyph-mask)"/>

  <!-- top sheen, kept inside the glyph -->
  <rect x="0" y="0" width="100" height="46" fill="url(#sheen)" opacity="0.5" mask="url(#glyph-mask)"/>

  <!-- light catching the top and bottom edges of the glass -->
  <g filter="url(#inner-light)">
    <g transform="{glyph_wrap}" fill="#000">{shapes}</g>
  </g>{rim_svg}
</svg>
"""

open(f"{out_dir}/app-icon-glass.svg", "w").write(icon(rim=True, scale=1))
open(f"{out_dir}/app-icon-glass-android.svg", "w").write(icon(rim=False, scale=1))
open(f"{out_dir}/app-icon-glass-maskable.svg", "w").write(icon(rim=False, scale=0.72))
print("ok")
